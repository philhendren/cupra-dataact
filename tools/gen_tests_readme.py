"""Generate tests/README.md: every test, what it checks, and links to each of its asserts.

    uv run python tools/gen_tests_readme.py           # rewrite tests/README.md
    uv run python tools/gen_tests_readme.py --check   # fail if it is out of date (CI)

Descriptions come from each test's docstring and the file's module docstring.
Asserts are `assert` statements, `pytest.raises(...)` blocks and mock `assert_*()` calls.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
README = TESTS / "README.md"
MAX_SNIPPET = 110


@dataclass
class Check:
    line: int
    text: str


@dataclass
class Test:
    name: str
    line: int
    doc: str
    cases: int
    checks: list[Check] = field(default_factory=list)


@dataclass
class TestFile:
    path: Path
    doc: str
    tests: list[Test]

    @property
    def case_count(self) -> int:
        return sum(t.cases for t in self.tests)

    @property
    def check_count(self) -> int:
        return sum(len(t.checks) for t in self.tests)


def snippet(source: str, node: ast.AST) -> str:
    text = re.sub(r"\s+", " ", ast.get_source_segment(source, node) or "").strip()
    text = text.replace("( ", "(").replace(" )", ")").replace("[ ", "[").replace(" ]", "]")
    return text if len(text) <= MAX_SNIPPET else text[: MAX_SNIPPET - 1] + "…"


def is_pytest_raises(node: ast.AST) -> bool:
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "raises"
        and isinstance(node.func.value, ast.Name)
        and node.func.value.id == "pytest"
    )


def checks_in(source: str, func: ast.AST) -> list[Check]:
    found: list[Check] = []
    for node in ast.walk(func):
        if isinstance(node, ast.Assert):
            found.append(Check(node.lineno, snippet(source, node)))
        elif isinstance(node, (ast.With, ast.AsyncWith)):
            for item in node.items:
                if is_pytest_raises(item.context_expr):
                    found.append(Check(item.context_expr.lineno, snippet(source, item.context_expr)))
        elif (
            isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr.startswith("assert_")
        ):
            found.append(Check(node.lineno, snippet(source, node)))
    return sorted(found, key=lambda c: c.line)


def case_count(func: ast.FunctionDef | ast.AsyncFunctionDef) -> int:
    count = 1
    for deco in func.decorator_list:
        if (
            isinstance(deco, ast.Call)
            and isinstance(deco.func, ast.Attribute)
            and deco.func.attr == "parametrize"
            and len(deco.args) >= 2
            and isinstance(deco.args[1], (ast.List, ast.Tuple))
        ):
            count *= len(deco.args[1].elts)
    return count


def parse(path: Path) -> TestFile:
    source = path.read_text()
    tree = ast.parse(source)
    tests = [
        Test(
            name=node.name,
            line=node.lineno,
            doc=(ast.get_docstring(node) or "").strip(),
            cases=case_count(node),
            checks=checks_in(source, node),
        )
        for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_")
    ]
    return TestFile(path, (ast.get_docstring(tree) or "").strip().splitlines()[0], tests)


def anchor(name: str) -> str:
    return name.lower().replace(".", "").replace(" ", "-")


def render(files: list[TestFile]) -> str:
    total_cases = sum(f.case_count for f in files)
    total_checks = sum(f.check_count for f in files)
    out = [
        "# Tests",
        "",
        "<!-- Generated by tools/gen_tests_readme.py from the test code. Do not edit by hand. -->",
        "",
        f"{total_cases} test cases ({sum(len(f.tests) for f in files)} test functions) and {total_checks} "
        "assertions. All run offline: the portal is mocked, either at the HTTP level (`aioresponses`) "
        "or by replacing the client.",
        "",
        "```sh",
        "uv sync                                  # install the pinned dev tools",
        "uv run pytest                            # run all tests",
        "uv run pytest tests/test_sensor.py -k best_soc",
        "uv run ruff check . && uv run ruff format --check .",
        "uv run python tools/gen_tests_readme.py  # regenerate this file",
        "```",
        "",
        "| File | Covers | Cases | Asserts |",
        "|---|---|--:|--:|",
    ]
    for f in files:
        out.append(f"| [{f.path.name}](#{anchor(f.path.name)}) | {f.doc} | {f.case_count} | {f.check_count} |")
    out.append("")
    out.append(
        "Shared fixtures live in [conftest.py](conftest.py): a mocked `DataActClient` for setup "
        "(`mock_client`) and for the config flow (`flow_client`), a `config_entry`, and helpers that "
        "fill a vehicle with sample data points."
    )

    for f in files:
        out += ["", f"## {f.path.name}", "", f.doc, ""]
        for t in f.tests:
            cases = f" · {t.cases} cases" if t.cases > 1 else ""
            out.append(f"### `{t.name}`")
            out.append("")
            out.append(f"[{f.path.name}:{t.line}]({f.path.name}#L{t.line}){cases}")
            out.append("")
            if t.doc:
                out += [t.doc, ""]
            for c in t.checks:
                out.append(f"- [L{c.line}]({f.path.name}#L{c.line}) `{c.text}`")
            if not t.checks:
                out.append("- _no assertions_")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if tests/README.md is out of date")
    args = parser.parse_args()

    files = [parse(p) for p in sorted(TESTS.glob("test_*.py"))]
    missing = [f"{f.path.name}::{t.name}" for f in files for t in f.tests if not t.doc]
    if missing:
        print("tests without a docstring:\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1

    content = render(files)
    if args.check:
        if not README.exists() or README.read_text() != content:
            print("tests/README.md is out of date: run `uv run python tools/gen_tests_readme.py`", file=sys.stderr)
            return 1
        return 0
    README.write_text(content)
    print(f"wrote {README.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
